/**
 * Dynamic icon resolver by string key
 */
export const NavIcon = ({ name, size = 18, className = '' }: { name: string; size?: number; className?: string }) => {
  switch (name) {
    case 'dashboard':
      return <DashboardIcon size={size} className={className} />;
    case 'tickets':
      return <TicketsIcon size={size} className={className} />;
    case 'knowledge-base':
    case 'book':
      return <BookOpenIcon size={size} className={className} />;
    case 'users':
      return <UsersIcon size={size} className={className} />;
    case 'teams':
      return <TeamsIcon size={size} className={className} />;
    case 'categories':
      return <CategoriesIcon size={size} className={className} />;
    case 'reports':
      return <ReportsIcon size={size} className={className} />;
    case 'notifications':
      return <NotificationsIcon size={size} className={className} />;
    case 'calendar':
      return <CalendarIcon size={size} className={className} />;
    case 'settings':
      return <SettingsIcon size={size} className={className} />;
    case 'plus':
      return <PlusIcon size={size} className={className} />;
    default:
      return <DashboardIcon size={size} className={className} />;
  }
};

